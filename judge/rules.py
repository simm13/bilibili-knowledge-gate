# ------------------------------------------------------------------ 匹配
def _is_ascii_token(w: str) -> bool:
    return all(ord(c) < 128 for c in w)


def _build_re(words):
    """CJK 词用子串匹配；纯 ASCII 词用词边界匹配（避免 api 命中 capital）"""
    parts = []
    for w in words:
        if _is_ascii_token(w):
            parts.append(r"(?<![a-z0-9])" + re.escape(w) + r"(?![a-z0-9])")
        else:
            parts.append(re.escape(w))
    return re.compile("|".join(parts), re.IGNORECASE)


GAME_TITLE_RE = _build_re(GAME_TITLES)
GAME_RE = _build_re(GAME_ALL)
ENTERTAIN_RE = _build_re(ENTERTAIN_WORDS)
KNOWLEDGE_STRONG_RE = _build_re(KNOWLEDGE_STRONG)
KNOWLEDGE_WEAK_RE = _build_re(KNOWLEDGE_WEAK)
KNOWLEDGE_RE = KNOWLEDGE_STRONG_RE          # 兼容旧引用：强白名单
GAME_WORD_SET = set(GAME_ALL)
KNOWLEDGE_WORD_SET = set(KNOWLEDGE_WORDS)
ENTERTAIN_WORD_SET = set(ENTERTAIN_WORDS)


def _hit(rx, text):
    m = rx.search(text)
    return m.group(0) if m else ""


def classify_text(text):
    """规则层裁决。返回 (knowledge, reason, source) 或 None（需 LLM）"""
    if not text:
        return None
    # 1) 具体游戏名最优先：游戏实况/游戏攻略/游戏教程都属于娱乐
    t = _hit(GAME_TITLE_RE, text)
    if t:
        return (False, "命中具体游戏名(%s)" % t[:12], "rule:game")
    # 2) 强知识白名单
    k = _hit(KNOWLEDGE_STRONG_RE, text)
    if k:
        return (True, "命中强知识白名单(%s)" % k[:12], "rule:knowledge")
    # 3) 娱乐黑名单
    e = _hit(ENTERTAIN_RE, text)
    if e:
        return (False, "命中娱乐黑名单(%s)" % e[:12], "rule:ent")
    # 4) 泛游戏词
    g = _hit(GAME_RE, text)
    if g:
        return (False, "命中游戏黑名单(%s)" % g[:12], "rule:game")
    # 5) 弱知识词不足以直接放行，交给 LLM
    return None


