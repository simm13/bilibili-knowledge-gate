def classify_category(text):
    """把内容细分类目：学科/技术/科普/技能/资讯/其他/娱乐/游戏（非知识类）"""
    if not text:
        return ""
    if _hit(GAME_TITLE_RE, text):
        return "游戏"
    if _hit(ENTERTAIN_RE, text):
        return "娱乐"
    if _hit(MATH_RE, text):
        return "数学"
    if _hit(PHYSICS_RE, text):
        return "物理"
    if _hit(SUBJECT_RE, text):
        return "学科"
    if _hit(TECH_RE, text):
        return "技术"
    if _hit(POP_SCI_RE, text):
        return "科普"
    if _hit(SKILL_RE, text):
        return "技能"
    if _hit(INFO_RE, text):
        return "资讯"
    return "其他"
